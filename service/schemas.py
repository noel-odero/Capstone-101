"""Request and response models. Field semantics are documented on the fields themselves."""
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, StrictInt

PROFILE_LENGTH = 7  # equals len(ml/simulation ANTIBIOTICS); the existing InferenceContext re-validates it.

Seed = Annotated[StrictInt, Field(ge=0, le=2**32 - 1)]
ResistanceProfile = Annotated[
    list[StrictInt],
    Field(
        min_length=PROFILE_LENGTH,
        max_length=PROFILE_LENGTH,
        description="Canonical antibiotic order; 0 = susceptible, 1 = resistant. No unknown values.",
    ),
]


class StrictRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ProfileRequest(StrictRequest):
    resistance_profile: ResistanceProfile


class RecommendRequest(StrictRequest):
    resistance_profile: ResistanceProfile
    last_action: StrictInt | None = Field(
        description="Previous action id (0-6), or null exactly when treatment_step is 0."
    )
    treatment_step: StrictInt = Field(description="Number of actions already taken (0-8).")


class SimulateRequest(StrictRequest):
    resistance_profile: ResistanceProfile
    strategy: Literal["ppo", "greedy"] = Field(
        description="'ppo' is the frozen PPO policy; 'greedy' is the existing GreedyPolicy, "
        "which samples uniformly among susceptible actions (public label: Random Susceptible Baseline)."
    )
    environment_seed: Seed | None = Field(default=None, description="Generated by the service when omitted.")
    policy_seed: Seed | None = Field(
        default=None,
        description="Seeds the baseline's tie-breaking RNG. Ignored by PPO (deterministic).",
    )


class CompareRequest(StrictRequest):
    resistance_profile: ResistanceProfile
    environment_seed: Seed | None = Field(default=None, description="Generated by the service when omitted.")
    policy_seed: Seed | None = Field(default=None, description="Baseline tie-breaking seed; PPO ignores it.")


class ErrorBody(BaseModel):
    code: str
    message: str
    request_id: str
    details: list[dict[str, Any]] | None = None


class ErrorResponse(BaseModel):
    error: ErrorBody


class HealthResponse(BaseModel):
    status: Literal["ok", "unavailable"]
    model_ready: bool
    service_version: str
    model_id: str | None = None
    checkpoint_sha256: str | None = None
    error_code: str | None = None
    message: str


class ModelResponse(BaseModel):
    manifest_version: int
    model_id: str
    algorithm: str
    checkpoint_sha256: str = Field(description="SHA-256 verified at load; the bytes loaded are the bytes hashed.")
    manifest_checkpoint_sha256: str
    interaction_data_sha256: str = Field(description="Pinned in the manifest and verified against the live simulator data at load.")
    scenario_id: str
    horizon: int
    antibiotic_order: list[str]
    observation: dict[str, Any]
    action_space: dict[str, Any]
    action_masking: dict[str, Any]
    inference: dict[str, Any]
    provenance_files: dict[str, str] = Field(description="Repository-relative paths recorded in the manifest.")
    transition_status_definitions: dict[str, str]
    service_version: str
    disclaimer: str


class Antibiotic(BaseModel):
    action_id: int
    name: str
    drug_class: str | None


class AntibioticsResponse(BaseModel):
    antibiotics: list[Antibiotic]
    resistance_encoding: dict[str, int]


class FeasibleAction(BaseModel):
    action_id: int
    antibiotic: str
    has_candidate_transition: bool = Field(
        description="True if the simulator has at least one modeled transition outcome for this action in this "
        "state. False means unsupported_no_candidate: the simulator leaves the profile unchanged for lack of data."
    )


class ProfileValidationResponse(BaseModel):
    valid: Literal[True] = True
    resistance_profile: list[int]
    resistant_antibiotics: list[str]
    susceptible_antibiotics: list[str]
    resistant_count: int
    susceptible_option_count: int
    feasible_actions: list[FeasibleAction]
    feasible_action_ids: list[int]
    is_terminal: bool
    terminal_reason: str | None
    horizon: int


class RecommendationResponse(BaseModel):
    status: Literal["recommended", "terminal"]
    is_terminal: bool
    terminal_reason: str | None
    resistance_profile: list[int]
    last_action_id: int | None
    last_action_antibiotic: str | None
    treatment_step: int
    action_id: int | None
    antibiotic: str | None
    feasible_actions: list[FeasibleAction]
    feasible_action_ids: list[int]
    transition_status: str | None
    has_candidate_transition: bool | None
    susceptible_option_count: int
    model_id: str
    checkpoint_sha256: str
    interpretation: str


class StateSnapshot(BaseModel):
    state_index: int = Field(description="0 is the initial state; k is the state after the k-th action.")
    treatment_step: int
    resistance_profile: list[int]
    resistant_antibiotics: list[str]
    resistant_count: int
    susceptible_count: int
    last_action_id: int | None
    last_action_antibiotic: str | None
    is_terminal: bool


class CandidateTransition(BaseModel):
    target_drug: str
    outcome: str
    source_ids: list[str]
    scenario_probability: float = Field(
        description="Probability under the simulator's scenario assumption, not an empirical estimate."
    )


class StepTrace(BaseModel):
    step_index: int
    treatment_step_before: int
    treatment_step_after: int
    resistance_profile_before: list[int]
    action_id: int
    antibiotic: str
    feasible_actions: list[FeasibleAction]
    selected_drug_susceptible: bool = Field(
        description="Simulator flag: the selected drug was susceptible in the pre-action state. Not clinical efficacy."
    )
    transition_status: str
    has_candidate_transition: bool
    candidate_transitions: list[CandidateTransition]
    selected_outcome: str | None
    selected_target_drug: str | None
    source_ids: list[str]
    selected_candidate_probability: float | None
    no_transition_probability: float | None
    transition_seed: int | None
    reward: float
    resistance_profile_after: list[int]
    newly_resistant_antibiotics: list[str]
    newly_susceptible_antibiotics: list[str]
    resistant_count_after: int
    susceptible_count_after: int
    is_terminal_after: bool
    termination_reason: str | None = Field(description="Set only on the step that ends the episode.")


class StrategyMetrics(BaseModel):
    cumulative_resistance_burden: float
    cumulative_reward: float
    treatment_steps: int
    initial_resistant_count: int
    final_resistant_count: int
    final_susceptible_count: int
    change_in_susceptible_count: int
    resistance_emergence_events: int
    resistance_emergence_rate: float | None
    susceptible_action_rate: float | None
    unsupported_step_count: int
    cumulative_antibiotic_exposure: int


class StrategyResult(BaseModel):
    strategy: Literal["ppo", "greedy"]
    display_label: str
    implementation: str
    initial_profile: list[int]
    final_profile: list[int]
    environment_seed: int
    policy_seed: int | None
    termination_reason: str
    states: list[StateSnapshot]
    steps: list[StepTrace]
    metrics: StrategyMetrics


class SeedConfiguration(BaseModel):
    environment_seed: int
    environment_seed_source: Literal["client", "service_generated"]
    policy_seed: int | None
    policy_seed_source: Literal["client", "service_generated", "not_applicable"]
    notes: list[str]


class Provenance(BaseModel):
    service_version: str
    model_id: str
    algorithm: str
    checkpoint_sha256: str
    interaction_data_sha256: str = Field(description="Hash of the transition data live in this run's simulator.")
    scenario_id: str
    horizon: int
    reward_specification: dict[str, Any]
    action_mask_rule: str
    antibiotic_order: list[str]
    evaluation_utility: str


class SimulationResponse(BaseModel):
    run_id: str
    kind: Literal["simulation"] = "simulation"
    created_at_utc: str
    provenance: Provenance
    seed_configuration: SeedConfiguration
    result: StrategyResult
    metric_definitions: dict[str, str]
    disclaimer: str


class SharedConfiguration(BaseModel):
    initial_profile: list[int]
    environment_seed: int
    scenario_id: str
    horizon: int
    interaction_data_sha256: str
    reward_specification: dict[str, Any]
    action_mask_configuration: dict[str, Any]


class TransitionSeedSchedule(BaseModel):
    shared_by_step_index: Literal[True]
    steps_compared: int
    meaning: str


class ObservedDivergence(BaseModel):
    steps_compared: int
    steps_with_same_action: int
    first_divergent_step: int | None = Field(
        description="First step whose action or resulting profile differs between strategies; null if none."
    )
    trajectories_identical: bool


class ComparisonContract(BaseModel):
    verified: Literal[True] = Field(description="Present only when every check passed; otherwise the request fails.")
    checks_passed: list[str]
    shared: SharedConfiguration
    transition_seed_schedule: TransitionSeedSchedule
    transition_outcomes_guaranteed_identical: Literal[False] = Field(
        description="Always false: a shared seed schedule does not guarantee identical transition outcomes."
    )
    observed: ObservedDivergence


class ComparisonResponse(BaseModel):
    run_id: str
    kind: Literal["comparison"] = "comparison"
    created_at_utc: str
    provenance: Provenance
    seed_configuration: SeedConfiguration
    pairing_semantics: str
    comparison_contract: ComparisonContract
    ppo: StrategyResult
    greedy: StrategyResult
    metric_definitions: dict[str, str]
    single_run_caveat: str
    disclaimer: str
